"""Render table rows and the repeated-answer chart from the held-out summary."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAMES = {
    "zero_shot": "Zero-shot", "few_shot": "Few-shot", "chain_of_thought": "Stepwise",
    "agent": "Inspection agent", "agent_no_feedback": "Withheld feedback",
}


def tex_rows(macro, rows):
    # \\newcommand expands inside a tabular; captions and discussion live in main.tex.
    body = "\n".join(" & ".join(map(str, fields)) + r" \\" for fields in rows)
    return "\\newcommand{\\" + macro + "}{%\n" + body + "\n}"


def main():
    stats = json.loads((ROOT / "results/test-v1/summary.json").read_text())["methods"]
    quality, sensitivity, efficiency, repetition = [], [], [], []
    for method, label in NAMES.items():
        m = stats[method]
        o = m["original_decisions"]
        d = m["diagnostic_decisions"]
        quality.append([label, o["keep"], o["review"], o["reject"], d["reject"], d["review"],
                        d["failed"], m["paired_keep_original_reject_diagnostic"]])
        counts = m["per_defect"]["excessive_repetition"]
        if counts["keep"] != 0 or sum(counts.values()) != 8:
            raise ValueError("The plotted diagnostic set must contain eight non-kept records.")
        pos = len(repetition)
        repetition.append(r"\RepeatBar" + f"{{{pos}}}{{{label}}}"
                          + "".join(f"{{{counts[outcome]}}}" for outcome in ("reject", "review", "failed")))
        policies = m["threshold_sensitivity"]
        sensitivity.append([label] + [
            f'{policies[p]["original_kept"]} / {policies[p]["diagnostic_kept"]}'
            for p in ("strict_all_2", "sum_at_least_7", "all_at_least_1")])
        efficiency.append([label, m["calls"], f'{m["prompt_tokens"]:,}', f'{m["completion_tokens"]:,}',
                           f'{m["mean_latency_seconds"]:.2f}', f'{m["median_latency_seconds"]:.2f}',
                           f'{m["cost_micro_cny"] / 1_000_000:.4f}'])
    output = [tex_rows("QualityRows", quality), tex_rows("ThresholdRows", sensitivity), tex_rows("CostRows", efficiency)]
    output.append(r"\newcommand{\RepeatedAnswerBars}{%" + "\n" + "\n".join(repetition) + "\n}")
    (ROOT / "report/latex/results.tex").write_text("% Generated by src/render_results.py\n" + "\n\n".join(output) + "\n")


if __name__ == "__main__":
    main()
